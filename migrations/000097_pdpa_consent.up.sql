-- ความยินยอม PDPA ระดับ "บัญชี" — ต่างจาก quotations.pdpa_consent (000044) ซึ่งเป็น
-- ความยินยอมต่อใบเสนอราคาหนึ่งใบที่ช่างติ๊กแทนลูกค้าหน้าเคาน์เตอร์. อันนี้เจ้าของ
-- บัญชีกดเอง ตอน login ครั้งแรก แล้วผูกกับบัญชีไป
--
-- เก็บเป็นแถวต่อการยอมรับหนึ่งครั้ง ไม่ใช่ธง boolean บน users เพราะ PDPA ต้องพิสูจน์
-- ย้อนหลังได้ว่า "ใคร ยอมรับข้อความไหน เมื่อไหร่ จากที่ไหน" ซึ่งธงตอบไม่ได้สักข้อ
-- และเมื่อบัมพ์เวอร์ชันข้อความ ประวัติการยอมรับรอบก่อนต้องไม่ถูกทับหาย
CREATE TABLE IF NOT EXISTS user_consents (
    id            SERIAL PRIMARY KEY,
    user_id       INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    consent_type  VARCHAR(50) NOT NULL DEFAULT 'pdpa',
    version       INT NOT NULL,
    -- สำเนาข้อความ ณ วินาทีที่กด. ข้อความต้นทางแก้ได้จากหน้าตั้งค่า การอ้างแค่เลข
    -- เวอร์ชันจึงไม่พอเป็นหลักฐาน — ถ้าใครแก้ข้อความโดยลืมบัมพ์เวอร์ชัน หลักฐานจะเพี้ยน
    text_snapshot TEXT NOT NULL DEFAULT '',
    ip            VARCHAR(100) NOT NULL DEFAULT '',
    user_agent    TEXT NOT NULL DEFAULT '',
    accepted_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- กดรัว ๆ หรือเปิดค้างไว้สองแท็บแล้วกดทั้งคู่ ต้องไม่กลายเป็นหลักฐานสองใบ
CREATE UNIQUE INDEX IF NOT EXISTS idx_user_consents_unique
    ON user_consents (user_id, consent_type, version);

CREATE INDEX IF NOT EXISTS idx_user_consents_user ON user_consents (user_id);

